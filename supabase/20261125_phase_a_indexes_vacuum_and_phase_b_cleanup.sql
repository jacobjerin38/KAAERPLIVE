-- 1. Hot covering index for ActivityLogs pagination & filtering (eliminates 77% of Disk Reads)
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_activity_logs_comp_created
    ON public.activity_logs (company_id, created_at DESC);

-- 2. Employee self-service & payslip history lookup on payroll_records
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_payroll_records_emp_created
    ON public.payroll_records (employee_id, created_at DESC);

-- 3. Leave date-range / overlap / ESSP status lookup
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_leaves_emp_status_dates
    ON public.leaves (employee_id, status, start_date, end_date);

-- 4. Overtime employee timeline lookup
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_overtime_requests_emp_created
    ON public.overtime_requests (employee_id, created_at DESC);

-- 5. Drop duplicate requester index on workflow_instances (keep idx_wf_instances_requester_id)
DROP INDEX CONCURRENTLY IF EXISTS public.idx_workflow_instances_requester;

